#!/usr/bin/env python3
"""Usage: python render.py specs/ep001.yaml [--out renders/ep001] [--stills 0,2,10] [--fast]
Writes <out>/<id>.mp4, <id>.wav, <id>.events.json, <id>.contact.png. Nothing is generated by AI."""
import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "lib"))
import scalezoom as sz  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("spec")
ap.add_argument("--out", default=None)
ap.add_argument("--stills", default=None, help="comma-separated times (s): write PNG stills and exit")
ap.add_argument("--fast", action="store_true", help="ultrafast encode (drafts)")
a = ap.parse_args()
ep = sz.load(a.spec)
out = Path(a.out or f"renders/{ep.spec['id']}")
out.mkdir(parents=True, exist_ok=True)
sid = ep.spec["id"]
ev = ep.events()
(out / f"{sid}.events.json").write_text(json.dumps(
    {"id": sid, "duration_s": ep.D, "fps": ep.FPS, "width": ep.W, "height": ep.H, "center_y": ep.cy,
     "ratio_universe_over_atom": ep.ratio, "label_coverage": round(ep.label_coverage()[0], 4),
     "label_gaps_s": ep.label_coverage()[1][:20], "events": ev}, indent=2, ensure_ascii=False))
if a.stills:
    for s in a.stills.split(","):
        ep.draw(float(s))
        ep.surf.write_to_png(str(out / f"still_{float(s):06.2f}.png"))
    sys.exit(0)
t0 = time.time()
lufs, peak = ep.write_audio(out / f"{sid}.wav")
print(f"audio: {lufs} LUFS, peak {peak} dBFS ({time.time() - t0:.1f}s)")
t1 = time.time()
n = ep.render(out / f"{sid}.mp4", out / f"{sid}.wav", preset="ultrafast" if a.fast else "veryfast")
print(f"video: {n} frames in {time.time() - t1:.1f}s")
ep.contact_sheet(out / f"{sid}.contact.png")
print("min label dwell (s):", min(e["label_dwell_s"] for e in ev), "| ratio:", ep.ratio)
